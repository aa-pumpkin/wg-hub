const browser = await chromium.launch()
async function ctx(opts = {}) {
  const c = await browser.newContext({ viewport: { width: 1280, height: 820 }, locale: 'de-DE', ...opts })
  const p = await c.newPage()
  p.on('pageerror', (e) => problems.push('pageerror: ' + e.message))
  p.on('console', (m) => {
    if (m.type() === 'error' && !/status of (400|401|403|404|409|410)/.test(m.text())) problems.push('console: ' + m.text())
  })
  return { c, p }
}
